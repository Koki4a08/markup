// Regenerates supabase/functions/_shared/email/assets.ts (run by hand, commit the output).
// Emails embed these as inline images (cid:), so clients that block remote images still show them.
//   logo:   apps/app/src-tauri/icons/128x128.png (shown at 28 px)
//   cursor: supabase/functions/_shared/email/cursor.png (48 px, shown at 24 px)
import { readFileSync, writeFileSync } from 'node:fs';

const read = (path) => {
  const png = readFileSync(new URL(path, import.meta.url));
  if (png.readUInt32BE(0) !== 0x89504e47) throw new Error(`${path} is not a PNG`);
  return png;
};
const logo = read('../apps/app/src-tauri/icons/128x128.png');
const cursor = read('../supabase/functions/_shared/email/cursor.png');
const target = new URL('../supabase/functions/_shared/email/assets.ts', import.meta.url);

writeFileSync(
  target,
  `// Generated by scripts/gen-email-assets.mjs. Do not edit.\n` +
    `export const LOGO_PNG_BASE64 =\n  '${logo.toString('base64')}';\n\n` +
    `export const CURSOR_PNG_BASE64 =\n  '${cursor.toString('base64')}';\n`,
);
console.log(`wrote assets.ts (logo ${logo.length} B, cursor ${cursor.length} B)`);
